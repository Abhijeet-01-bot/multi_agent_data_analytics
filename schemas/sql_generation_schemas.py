from typing import Any

from pydantic import (
    BaseModel,
    Field,
    model_validator,
)

from schemas.sql_schemas import (
    QueryExecutionResult,
    SQLValidationResult,
)


class GeneratedSQLQuery(BaseModel):
    """
    Candidate SQL generated by the SQL Agent.
    """

    task_id: str

    sql: str = Field(
        min_length=1,
        description=(
            "One parameterized, read-only SQLite "
            "SELECT statement."
        ),
    )

    parameters: dict[str, Any] = Field(
        default_factory=dict
    )

    referenced_tables: list[str] = Field(
        default_factory=list
    )

    expected_columns: list[str] = Field(
        default_factory=list
    )

    explanation: str

    assumptions: list[str] = Field(
        default_factory=list
    )


class SQLCorrectionContext(BaseModel):
    """
    Information supplied to the SQL Agent when a previous
    query failed validation or execution.
    """

    attempt_number: int = Field(
        ge=1
    )

    previous_sql: str

    previous_parameters: dict[str, Any] = Field(
        default_factory=dict
    )

    validation_errors: list[str] = Field(
        default_factory=list
    )

    execution_errors: list[str] = Field(
        default_factory=list
    )


class SQLTaskResult(BaseModel):
    """
    Final result of SQL generation, validation,
    correction, and execution for one task.
    """

    success: bool

    task_id: str

    attempts: int = Field(
        ge=1
    )

    query: GeneratedSQLQuery | None = None

    validation: SQLValidationResult | None = None

    execution: QueryExecutionResult | None = None

    correction_history: list[
        SQLCorrectionContext
    ] = Field(
        default_factory=list
    )

    errors: list[str] = Field(
        default_factory=list
    )
    warnings: list[str] = Field(
    default_factory=list
    )

    @model_validator(mode="after")
    def validate_success_result(
        self,
    ) -> "SQLTaskResult":
        if self.success:
            if self.query is None:
                raise ValueError(
                    "A successful SQL task must contain "
                    "the generated query."
                )

            if self.validation is None:
                raise ValueError(
                    "A successful SQL task must contain "
                    "the validation result."
                )

            if self.execution is None:
                raise ValueError(
                    "A successful SQL task must contain "
                    "the execution result."
                )

            if not self.validation.is_valid:
                raise ValueError(
                    "A successful SQL task cannot have "
                    "failed SQL validation."
                )

            if not self.execution.success:
                raise ValueError(
                    "A successful SQL task cannot have "
                    "failed execution."
                )

        return self